CREATE TABLE vets (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, first_name VARCHAR(30), last_name VARCHAR(30));
CREATE TABLE specialties (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80));
CREATE TABLE vet_specialties (vet_id INTEGER NOT NULL REFERENCES vets(id), specialty_id INTEGER NOT NULL REFERENCES specialties(id));
CREATE TABLE service_skills (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) NOT NULL);
CREATE TABLE housekeepers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) NOT NULL, telephone VARCHAR(20) NOT NULL,
  introduction VARCHAR(500), experience_years INTEGER, rating DECIMAL(2,1), status VARCHAR(30), service_district VARCHAR(120)
);
CREATE TABLE housekeeper_skills (
  housekeeper_id INTEGER NOT NULL REFERENCES housekeepers(id) ON DELETE CASCADE,
  skill_id INTEGER NOT NULL REFERENCES service_skills(id), PRIMARY KEY(housekeeper_id,skill_id)
);
CREATE TABLE service_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, description VARCHAR(500),
  skill_id INTEGER NOT NULL REFERENCES service_skills(id), pricing_type VARCHAR(30), unit_price DECIMAL(10,2),
  minimum_units DECIMAL(10,2), estimated_minutes INTEGER, enabled BOOLEAN
);
CREATE TABLE worker_schedules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, housekeeper_id INTEGER NOT NULL REFERENCES housekeepers(id) ON DELETE CASCADE,
  service_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL, status VARCHAR(30), reservation_key VARCHAR(80) UNIQUE,
  CHECK (end_time > start_time)
);
CREATE INDEX idx_worker_schedule_lookup ON worker_schedules(housekeeper_id,service_date,start_time,end_time);
