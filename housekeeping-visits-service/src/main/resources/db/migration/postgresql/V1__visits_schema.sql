CREATE TABLE visits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pet_id INTEGER NOT NULL,
  visit_date DATE, description VARCHAR(8192)
);
CREATE INDEX visits_pet_id ON visits(pet_id);
CREATE TABLE service_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT DEFAULT 0 NOT NULL,
  idempotency_key VARCHAR(80) UNIQUE, reservation_key VARCHAR(80) UNIQUE, booking_number VARCHAR(30) UNIQUE,
  customer_id INTEGER NOT NULL, address_id INTEGER NOT NULL, service_item_id INTEGER NOT NULL, housekeeper_id INTEGER,
  service_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
  quantity DECIMAL(10,2) NOT NULL CHECK(quantity > 0), unit_price DECIMAL(10,2) NOT NULL CHECK(unit_price > 0),
  total_price DECIMAL(10,2) NOT NULL CHECK(total_price > 0), status VARCHAR(30) NOT NULL,
  customer_remark VARCHAR(500), created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
  CHECK(end_time > start_time)
);
CREATE INDEX idx_booking_customer_time ON service_bookings(customer_id,created_at DESC);
CREATE INDEX idx_booking_worker_time ON service_bookings(housekeeper_id,service_date,start_time);
CREATE TABLE service_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL UNIQUE REFERENCES service_bookings(id),
  customer_id INTEGER NOT NULL, housekeeper_id INTEGER NOT NULL, score INTEGER NOT NULL CHECK(score BETWEEN 1 AND 5),
  content VARCHAR(1000), created_at TIMESTAMP NOT NULL
);
CREATE TABLE domain_event_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, aggregate_id VARCHAR(80) NOT NULL,
  event_type VARCHAR(80) NOT NULL, payload VARCHAR(4000) NOT NULL,
  created_at TIMESTAMP NOT NULL, published_at TIMESTAMP
);
CREATE INDEX idx_outbox_unpublished ON domain_event_outbox(published_at,created_at);
