CREATE TABLE owners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(30), last_name VARCHAR(30), address VARCHAR(255), city VARCHAR(80), telephone VARCHAR(20)
);
CREATE INDEX owners_last_name ON owners(last_name);
CREATE TABLE types (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80));
CREATE TABLE pets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(30), birth_date DATE,
  type_id INTEGER NOT NULL REFERENCES types(id), owner_id INTEGER NOT NULL REFERENCES owners(id)
);
CREATE INDEX pets_name ON pets(name);
CREATE TABLE customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL, telephone VARCHAR(20) NOT NULL, email VARCHAR(120)
);
CREATE TABLE service_addresses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id), contact_name VARCHAR(80) NOT NULL,
  telephone VARCHAR(20) NOT NULL, city VARCHAR(80) NOT NULL, district VARCHAR(80) NOT NULL,
  detail_address VARCHAR(255) NOT NULL, access_instruction VARCHAR(500), default_address BOOLEAN DEFAULT FALSE
);
CREATE INDEX idx_service_address_customer ON service_addresses(customer_id);

